// Helper query functions
export function getToolBySlug(slug: string): ToolRegistryItem | undefined {
  return MASTER_TOOL_REGISTRY.find((t) => t.slug === slug || t.id === slug);
}

export function getToolsByCategory(category: MasterToolCategory): ToolRegistryItem[] {
  return MASTER_TOOL_REGISTRY.filter((t) => t.category === category);
}

export function getRelatedTools(toolSlug: string, count = 4): ToolRegistryItem[] {
  const current = getToolBySlug(toolSlug);
  if (!current) return MASTER_TOOL_REGISTRY.slice(0, count);

  if (current.relatedTools && current.relatedTools.length > 0) {
    const list = current.relatedTools
      .map((slug) => getToolBySlug(slug))
      .filter((t): t is ToolRegistryItem => Boolean(t));
    if (list.length >= count) return list.slice(0, count);
  }

  // Fallback to same category
  return MASTER_TOOL_REGISTRY.filter(
    (t) => t.category === current.category && t.slug !== current.slug
  ).slice(0, count);
}

export function searchToolRegistry(queryStr: string): ToolRegistryItem[] {
  const q = queryStr.toLowerCase().trim();
  if (!q) return MASTER_TOOL_REGISTRY;

  return MASTER_TOOL_REGISTRY.filter((tool) => {
    return (
      tool.name.toLowerCase().includes(q) ||
      tool.shortDescription.toLowerCase().includes(q) ||
      tool.description.toLowerCase().includes(q) ||
      tool.category.toLowerCase().includes(q) ||
      tool.tags.some((tag) => tag.toLowerCase().includes(q))
    );
  });
}
